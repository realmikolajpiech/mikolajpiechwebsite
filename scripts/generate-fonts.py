"""Regenerate committed EN/PL fonts: pip install fonttools==4.60.2 brotli==1.2.1.

Normal builds use the committed WOFF2 assets and do not require Python packages.
Keep the original outlines, metrics, OpenType features, and variable weight axis.
"""
from pathlib import Path
import json
import shutil
from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'assets/fonts'
OUTPUT.mkdir(parents=True, exist_ok=True)

characters = set(chr(code) for code in range(32, 127))
characters.update('ĄĆĘŁŃÓŚŹŻąćęłńóśźż–—‘’“”•…€™→↗')
for source in [*ROOT.glob('content/*.json'), *ROOT.glob('data/*.ts'), *ROOT.glob('pages/*.tsx'), *ROOT.glob('components/*.tsx')]:
    text = source.read_text()
    if source.suffix == '.json':
        text = json.dumps(json.loads(text), ensure_ascii=False)
    characters.update(text)
unicodes = {ord(character) for character in characters}

manrope = ROOT / 'node_modules/@fontsource-variable/manrope'
serif = ROOT / 'node_modules/@fontsource/instrument-serif'
faces = [
    ('manrope-latin', 'Manrope', 'normal', '200 800', [manrope / 'files/manrope-latin-wght-normal.woff2']),
    ('manrope-latin-ext', 'Manrope', 'normal', '200 800', [manrope / 'files/manrope-latin-ext-wght-normal.woff2']),
    ('instrument-serif-normal', 'Instrument Serif', 'normal', '400', [serif / f'files/instrument-serif-{part}-400-normal.woff2' for part in ['latin', 'latin-ext']]),
    ('instrument-serif-italic', 'Instrument Serif', 'italic', '400', [serif / f'files/instrument-serif-{part}-400-italic.woff2' for part in ['latin', 'latin-ext']]),
]

css = ['/* Generated by scripts/generate-fonts.py. Font licences: assets/fonts/. */']
for name, family, style, weight, sources in faces:
    font = Merger().merge([str(source) for source in sources]) if len(sources) > 1 else TTFont(sources[0])
    # Keep Latin-1 in body text for names and text entered in the form.
    requested = unicodes | set(range(32, 256)) if family == 'Manrope' else unicodes
    required = requested & set(font.getBestCmap())
    if name == 'manrope-latin-ext':
        required = {code for code in required if code >= 0x100}
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    # Display serif outlines use browser rasterization instead of embedded grid hints.
    options.hinting = family == 'Manrope'
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=required)
    subsetter.subset(font)
    assert required <= set(font.getBestCmap()), f'{name}: a supported character was lost'
    font.flavor = 'woff2'
    font.recalcTimestamp = False
    font.save(OUTPUT / f'{name}.woff2')
    codes = sorted(font.getBestCmap())
    ranges = []
    start = end = codes[0]
    for code in codes[1:]:
        if code == end + 1:
            end = code
        else:
            ranges.append(f'U+{start:X}' + (f'-{end:X}' if end > start else ''))
            start = end = code
    ranges.append(f'U+{start:X}' + (f'-{end:X}' if end > start else ''))
    css.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-weight: {weight};
  font-display: swap;
  src: url('./assets/fonts/{name}.woff2') format('woff2');
  unicode-range: {','.join(ranges)};
}}""")
    print(f'{name}: {(OUTPUT / f"{name}.woff2").stat().st_size / 1024:.1f} KiB')

shutil.copyfile(manrope / 'LICENSE', OUTPUT / 'Manrope-OFL.txt')
shutil.copyfile(serif / 'LICENSE', OUTPUT / 'Instrument-Serif-OFL.txt')
(ROOT / 'fonts.css').write_text('\n\n'.join(css) + '\n')
